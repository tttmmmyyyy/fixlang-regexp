// Writes `internal/case_fold.fix`: the characters JavaScript's `i` flag takes for one another.
//
// Without the `u` flag, JavaScript compares two characters under `i` by their canonical forms
// (ECMAScript, Canonicalize): a UTF-16 code unit's canonical form is its upper case, except that a
// code unit whose upper case is more than one code unit, or whose upper case falls below U+0080
// from U+0080 upward, is its own canonical form. The table lists every code unit whose canonical
// form some other code unit shares.
//
// Run with Node from the root of the repository: `node tools/case_fold.js`.

"use strict";
const fs = require("fs");

function canonical(unit) {
    const upper = String.fromCharCode(unit).toUpperCase();
    if (upper.length != 1) return unit;
    const folded = upper.charCodeAt(0);
    if (unit >= 0x80 && folded < 0x80) return unit;
    return folded;
}

const groups = new Map();
for (let unit = 0; unit < 0x10000; unit++) {
    if (unit >= 0xd800 && unit <= 0xdfff) continue;
    const key = canonical(unit);
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(unit);
}
const pairs = [];
for (const [key, units] of groups) {
    if (units.length < 2) continue;
    for (const unit of units) pairs.push([unit, key]);
}
pairs.sort((a, b) => a[0] - b[0]);

const lines = [];
for (let i = 0; i < pairs.length; i += 6) {
    lines.push("    " + pairs.slice(i, i + 6).map(([unit, key]) => unit + ", " + key).join(", "));
}

const source = `// The characters JavaScript's \`i\` flag takes for one another. This is internal module of \`RegExp\`.
//
// Generated by \`node tools/case_fold.js\`; edit that script rather than this file.
module RegExp._Internal.CaseFold;

import Std::{Array, I64, Array::{@, @size, push_back}, Iterator::{fold, range}};

// The UTF-16 code units that share their canonical form with another code unit, each followed by
// that canonical form, in ascending order of the code units.
_table: Array I64;
_table = [
${lines.join(",\n")}
];

// The UTF-16 code units the \`i\` flag of JavaScript takes for \`unit\`: \`unit\` itself and every code
// unit of the same canonical form, in ascending order.
same_case_units: I64 -> Array I64;
same_case_units = |unit| (
    let count = _table.@size / 2;
    let found = _find(unit, 0, count);
    if found < 0 { [unit] };
    let key = _table.@(2 * found + 1);
    range(0, count).fold([], |i, units|
        if _table.@(2 * i + 1) == key { units.push_back(_table.@(2 * i)) } else { units }
    )
);

// The index of the entry of \`_table\` for \`unit\` among the entries from \`begin\` up to \`end\`, or
// \`-1\` where none of them is for \`unit\`.
_find: I64 -> I64 -> I64 -> I64;
_find = |unit, begin, end| (
    if begin >= end { -1 };
    let middle = (begin + end) / 2;
    let found = _table.@(2 * middle);
    if found == unit { middle };
    if found < unit { _find(unit, middle + 1, end) } else { _find(unit, begin, middle) }
);
`;
fs.writeFileSync("internal/case_fold.fix", source);
