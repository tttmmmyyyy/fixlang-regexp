// Writes `test_js_cases.fix`: patterns and strings drawn at random, each with every match
// JavaScript's `String.prototype.matchAll` finds and where each group of the match stands, and with
// the match `RegExp.prototype.exec` finds from a position drawn at random.
//
// Run with Node from the root of the repository: `node tools/js_cases.js`.

"use strict";
const fs = require("fs");
const vm = require("vm");

const CASES = 3000;

// A small generator of 32-bit numbers (mulberry32), so that the file comes out the same each time.
let seed = 20261010;
function next() {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = seed;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const below = (n) => Math.floor(next() * n);
const oneOf = (items) => items[below(items.length)];

const LETTERS = ["a", "b", "c", "x", " ", "\n", "1"];
const PLAIN = ["a", "b", "c", "x", ".", "[ab]", "[^a]", "[a-c]", "\\d", "\\w", "\\s", "\\W"];
const REPEATS = [
    "", "", "", "", "", "*", "+", "?", "{2}", "{1,2}", "{2,}", "{0,2}", "{0,}", "{1}", "{0}", "{3}", "{3,4}"
];

function atom(depth) {
    const draw = below(10);
    if (draw < 2 && depth < 2) return "(" + alternatives(depth + 1) + ")";
    if (draw == 2) return oneOf(["^", "$"]);
    return oneOf(PLAIN);
}

function piece(depth) {
    const a = atom(depth);
    if (a == "^" || a == "$") return a;
    const repeat = oneOf(REPEATS);
    const lazy = repeat != "" && below(3) == 0 ? "?" : "";
    return a + repeat + lazy;
}

function run(depth) {
    let pattern = "";
    const count = below(depth == 0 ? 4 : 3) + (depth == 0 ? 1 : 0);
    for (let i = 0; i < count; i++) pattern += piece(depth);
    return pattern;
}

function alternatives(depth) {
    let pattern = run(depth);
    while (below(3) == 0) pattern += "|" + run(depth);
    return pattern;
}

function target() {
    let text = "";
    const length = below(20);
    for (let i = 0; i < length; i++) text += oneOf(LETTERS);
    return text;
}

// A string literal of Fix holding `text`.
function literal(text) {
    return '"' + text.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n") + '"';
}

// Where each group of a match stands, as Fix writes it.
function groups(m) {
    const stretches = m.indices.map((stretch) =>
        stretch ? "(" + stretch[0] + ", " + stretch[1] + ")" : "(-1, -1)"
    );
    return "[" + stretches.join(", ") + "]";
}

// What JavaScript finds: every match, and the match found from `from`. A pattern JavaScript's
// backtracking takes too long over is given up, which `null` stands for.
function answers(pattern, text, from) {
    const script = `
        const all = [...text.matchAll(new RegExp(pattern, "gd"))];
        const re = new RegExp(pattern, "gd");
        re.lastIndex = from;
        ({ all, first: re.exec(text) });`;
    try {
        return vm.runInNewContext(script, { pattern, text, from }, { timeout: 1000 });
    } catch (e) {
        if (e.code == "ERR_SCRIPT_EXECUTION_TIMEOUT") return null;
        throw e;
    }
}

const rows = [];
while (rows.length < CASES) {
    const pattern = alternatives(0);
    const text = target();
    const from = below(text.length + 2);
    const found = answers(pattern, text, from);
    if (found == null) continue;
    const matches = "[" + found.all.map(groups).join(", ") + "]";
    const first = found.first ? "some(" + groups(found.first) + ")" : "none()";
    rows.push("    (" + [literal(pattern), literal(text), matches, from, first].join(", ") + ")");
}

const source = `// Patterns and strings drawn at random, each with every match JavaScript finds in the string and
// where each group of the match stands, \`(-1, -1)\` standing for a group that captured nothing,
// together with a position and the match JavaScript finds beginning at or after it.
//
// Generated by \`node tools/js_cases.js\`; edit that script rather than this file.
module Test.JsCases;

_js_cases: Array (String, String, Array (Array (I64, I64)), I64, Option (Array (I64, I64)));
_js_cases = [
${rows.join(",\n")}
];
`;
fs.writeFileSync("test_js_cases.fix", source);
